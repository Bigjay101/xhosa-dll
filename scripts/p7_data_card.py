"""P7.3 Generate DATA_CARD.md from the results files (Member A).

Run after P1-P6. Then add the hand-written "Gotchas" paragraph at the end.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from src.config import P, ROOT, base_parser, load_config  # noqa: E402
from src.io_utils import get_logger  # noqa: E402


def table(path: Path, max_rows: int = 40) -> str:
    if not path.exists():
        return f"_missing: {path.name}_\n"
    df = pd.read_csv(path)
    if df.empty:
        return "_empty_\n"
    df = df.head(max_rows)
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "---|" * len(df.columns)
    rows = ["| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows]) + "\n"


def main() -> None:
    args = base_parser(__doc__).parse_args()
    cfg = load_config(args.config, smoke=args.smoke)
    log = get_logger(cfg, "p7_data_card")
    res = lambda name: P(cfg, "results", name)  # noqa: E731
    hist = P(cfg, "processed", "hist_chunks.parquet")
    modern = P(cfg, "processed", "modern_chunks.parquet")
    parts = ["# DATA CARD -- NLP Project 2 (generated by scripts/p7_data_card.py)\n",
             "Handbook P7.3. Regenerate after any data change; never edit the generated tables by hand.\n",
             "## How to load\n",
             "```python\nfrom src.data_api import load_condition, load_lexicon\n"
             "h = load_condition('H-orig')            # historical test chunks, standard columns\n"
             "m = load_condition('M1-orig', 'depth')  # first 500 modern test chunks by sample_rank\n```\n",
             "## Sources and versions\nSee DATA_SOURCES.md.\n",
             "## Counts at every stage (X0)\n", table(res("X0_data_stats.csv"), 60),
             "## Sanity checks S1-S4\n", table(res("sanity_log.csv")),
             "## Language filter\n", table(res("langid_eval.csv")),
             "## Deduplication\n", table(res("dedup_report.csv")),
             "## Unresolved edition dates\n", table(res("meta_unresolved.csv"), 20)]
    if hist.exists():
        h = pd.read_parquet(hist)
        parts += ["## Historical chunks by split and eval set\n",
                  table_from_df(h.groupby(["source", "split", "eval_set"]).size().reset_index(name="n_chunks"))]
    if modern.exists():
        m = pd.read_parquet(modern)
        parts += ["## Modern chunks\n", table_from_df(m.groupby(["source", "role"]).size().reset_index(name="n_chunks"))]
    parts += ["## Tokenizer metrics (X1)\n", table(res("X1_summary.csv"), 80),
              "## Column definitions\nSee handbook D6.4 (schemas) and D6.5 (logs).\n",
              "## How each CHECK was resolved\nSee decision_log.md.\n",
              "## Gotchas (written by Jordan)\n_TODO: anything B and C must know about the data._\n"]
    out = (ROOT / "DATA_CARD.md") if not args.smoke else P(cfg, "results", "DATA_CARD_smoke.md", mkdir=True)
    out.write_text("\n".join(parts), encoding="utf-8")
    log.info("wrote %s", out)


def table_from_df(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "---|" * len(df.columns)
    rows = ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows]) + "\n"


if __name__ == "__main__":
    main()
